DECLARE @STATUS VARCHAR(2);
DECLARE @PEDIDO VARCHAR(10);
DECLARE @CHAVE_NF VARCHAR(100);
DECLARE @STATUS2 VARCHAR(100);

BEGIN
	SET NOCOUNT ON
	DECLARE TB02030_CURSOR_CHAVENOTA_OBS CURSOR FOR

	SELECT 
		TB02030_STATUS,
		TB02030_CODIGO,
		TB02091_NUMNFE,
		TB02130_STATUS

	FROM TB02030
	LEFT JOIN TB02130 ON TB02130_CODIGO = TB02030_CODIGO AND TB02130_TIPO = 'C'
	LEFT JOIN TB02091 ON TB02091_NTFISC = TB02030_NTFISC
	WHERE TB02130_STATUS IN ('19', '46') 

	OPEN TB02030_CURSOR_CHAVENOTA_OBS FETCH TB02030_CURSOR_CHAVENOTA_OBS
	INTO @STATUS, @PEDIDO, @CHAVE_NF,@STATUS2
	WHILE @@FETCH_STATUS = 0
	
	BEGIN
		IF @STATUS2 = '46' 
			UPDATE TB02130
				SET TB02130_OBS = @CHAVE_NF
				WHERE TB02130_CODIGO = @PEDIDO
				AND TB02130_TIPO = 'C' 
				AND TB02130_STATUS ='46'
				AND TB02130_OBS IS NULL
		OR @STATUS2 = '19' 
			UPDATE TB02130
				SET TB02130_OBS = @CHAVE_NF
				WHERE TB02130_CODIGO = @PEDIDO
				AND TB02130_TIPO = 'C' 
				AND TB02130_STATUS ='19'
				AND TB02130_OBS IS NULL

	FETCH NEXT FROM TB02030_CURSOR_CHAVENOTA_OBS
	INTO @STATUS, @PEDIDO, @CHAVE_NF,@STATUS2

	END

	CLOSE TB02030_CURSOR_CHAVENOTA_OBS
	DEALLOCATE TB02030_CURSOR_CHAVENOTA_OBS

END

GO
